/* Sirpeltric BG · batch export from the index page.
   Each selected scene opens (one at a time) in the small live preview frame with ?batch=<format>, exports itself and posts
   the file back here (see runBatch in _src/core.js). Files are saved one by one or collected into one ZIP.
   Not generated by build.php — edit this file directly. */
(() => {
  const root = document.getElementById('batch'); if (!root) return;
  const $ = s => root.querySelector(s), $$ = s => [...root.querySelectorAll(s)];
  const scenes = $$('input[name=scene]').map(i => ({ input: i, id: i.value, href: i.dataset.href, title: i.dataset.title }));
  const runBtn = $('#bRun'), stopBtn = $('#bStop'), list = $('#bList'), bar = $('#bBar'), sum = $('#bSum'), frameBox = $('#bFrame'), frameCap = $('#bCap');
  const fmtLabel = { 'glb-baked': '.glb · baked', 'glb-instanced': '.glb · instanced', obj: '.obj + .mtl', stl: '.stl' };
  let running = false, cancel = false;

  const selected = () => scenes.filter(s => s.input.checked);
  const opt = n => (root.querySelector(`input[name=${n}]:checked`) || {}).value;
  function sync() {
    const n = selected().length, f = opt('format');
    runBtn.textContent = n ? `Export ${n} scene${n > 1 ? 's' : ''} · ${fmtLabel[f]}` : 'Pick at least one scene';
    runBtn.disabled = running || !n;
    $('#bDetail').hidden = f === 'glb-instanced';                       // detail applies to baked .glb, .obj and .stl
  }
  root.addEventListener('change', sync);
  $('#bAll').onclick = () => { const all = selected().length < scenes.length; scenes.forEach(s => s.input.checked = all); sync(); };

  const mb = b => (b / 1048576).toFixed(b > 10485760 ? 0 : 1) + ' MB';
  function save(blob, name) { const a = document.createElement('a'); a.href = URL.createObjectURL(blob); a.download = name; document.body.appendChild(a); a.click(); a.remove(); setTimeout(() => URL.revokeObjectURL(a.href), 60000); }
  const loadZip = () => window.JSZip ? Promise.resolve() : new Promise((res, rej) => { const s = document.createElement('script'); s.src = 'https://cdn.jsdelivr.net/npm/jszip@3.10.1/dist/jszip.min.js'; s.onload = res; s.onerror = () => rej(new Error('JSZip could not load (offline?)')); document.head.appendChild(s); });

  function row(sc) {
    const li = document.createElement('li'); li.innerHTML = `<b></b><span class="st">waiting</span>`; li.querySelector('b').textContent = sc.title; list.appendChild(li);
    return (state, text) => { li.className = state; li.querySelector('.st').textContent = text; };
  }
  /** load one scene in the preview frame, export, resolve with its files */
  function runOne(sc, params, onMsg) {
    return new Promise((resolve, reject) => {
      const files = [], ifr = document.createElement('iframe');
      ifr.title = 'Exporting ' + sc.title; ifr.src = sc.href + '?' + params;
      const kill = () => { window.removeEventListener('message', onMessage); clearTimeout(timer); clearInterval(watch); ifr.remove(); };
      const timer = setTimeout(() => { kill(); reject(new Error('timed out')); }, 20 * 60 * 1000);
      const watch = setInterval(() => { if (cancel) { kill(); reject(new Error('stopped')); } }, 300);
      function onMessage(e) {
        const d = e.data; if (!d || d.source !== 'sirpeltric' || e.source !== ifr.contentWindow) return;
        if (d.type === 'sp-progress') onMsg(d.message);
        else if (d.type === 'sp-file') { files.push({ name: d.name, blob: d.blob }); onMsg('received ' + d.name); }
        else if (d.type === 'sp-done') { kill(); resolve(files); }
        else if (d.type === 'sp-error') { kill(); reject(new Error(d.message)); }
      }
      window.addEventListener('message', onMessage);
      frameBox.replaceChildren(ifr); frameCap.textContent = sc.title;
    });
  }

  runBtn.onclick = async () => {
    const todo = selected(); if (!todo.length || running) return;
    const f = opt('format'), out = opt('output'), [format, glb] = f.split('-');
    const params = new URLSearchParams({ batch: format, ...(glb ? { glb } : {}), detail: opt('detail') || 'medium' }).toString();
    running = true; cancel = false; sync(); stopBtn.hidden = false; root.classList.add('busy'); list.replaceChildren(); bar.style.width = '0%';
    const rows = todo.map(row), all = []; let done = 0, failed = 0, bytes = 0;
    if (out === 'zip') { try { await loadZip(); } catch (e) { sum.textContent = e.message; running = false; sync(); return; } }
    for (let i = 0; i < todo.length && !cancel; i++) {
      const set = rows[i]; set('run', 'loading scene…');
      try {
        const files = await runOne(todo[i], params, m => set('run', m));
        const size = files.reduce((a, x) => a + x.blob.size, 0); bytes += size; done++;
        if (out === 'zip') all.push(...files); else files.forEach(x => save(x.blob, x.name));
        set('ok', `${files.map(x => x.name.split('.').pop()).join(' + ')} · ${mb(size)}`);
      } catch (e) { failed++; set('err', e.message === 'stopped' ? 'stopped' : 'failed: ' + e.message); }
      bar.style.width = ((i + 1) / todo.length * 100) + '%';
      sum.textContent = `${done} of ${todo.length} done${failed ? ` · ${failed} failed` : ''} · ${mb(bytes)}`;
    }
    frameBox.replaceChildren(); frameCap.textContent = cancel ? 'Stopped' : 'Finished';
    if (out === 'zip' && all.length && !cancel) {
      sum.textContent = `Packing ${all.length} file${all.length > 1 ? 's' : ''} into one ZIP…`;
      const zip = new JSZip(); all.forEach(x => zip.file(x.name, x.blob));
      const blob = await zip.generateAsync({ type: 'blob', compression: 'STORE', streamFiles: true });
      save(blob, `sirpeltric_${f}_${all.length}-files.zip`);
      sum.textContent = `Saved one ZIP · ${all.length} files · ${mb(blob.size)}${failed ? ` · ${failed} failed` : ''}`;
    } else if (!cancel) sum.textContent = `Saved ${done} file${done === 1 ? '' : 's'} · ${mb(bytes)}${failed ? ` · ${failed} failed` : ''}`;
    running = false; stopBtn.hidden = true; root.classList.remove('busy'); sync();
  };
  stopBtn.onclick = () => { cancel = true; sum.textContent = 'Stopping after the current step…'; };
  sync();
})();
