<?php
/**
 * Sirpeltric BG — build (php build.php):
 *   one folder per background:  bgN-name/bgN-name.html (single file, open by double-click)
 *                               bgN-name/bgN-name-prompt.md (complete prompt)
 *                               bgN-name/references/ + references.md (from: php _src/export-references.php)
 *   index.html at the root lists everything.
 */
$src = __DIR__ . '/_src';
$out = __DIR__;

$bgs = [
    ['bg1', 'bg1-world-reveal',    'BG 1 · World reveal — 360° turn',          'Scenes 3–4 · 1960s'],
    ['bg2', 'bg2-earth-zoom-globe', 'BG 2 · Earth zoom out + Globe 360°',       'Scenes 7–9 · base → 1950s'],
    ['bg3', 'bg3-underwater',       'BG 3 · Underwater',                        'Scene 10 · 1960s graphic sea → crack to 1970s'],
    ['bg4', 'bg4-mirrored',         'BG 4 · Mirrored background',               'Scenes 11–18 · 1970s → 1945 close-up → 1980s → 1990s → 4-box colour'],
    ['bg5', 'bg5-hobby',            'BG 5 · Hobby background',                  'Scenes 19–20 · full colour'],
    ['bg6', 'bg6-forward-pathway',  'BG 6 · Forward pathway — Scene 22',        'Scenes 21–24 · colour → grey warp → black'],
];

$tpl    = file_get_contents("$src/template.html");
$core   = preg_replace('/^export function startApp/m', 'function startApp', file_get_contents("$src/core.js"));
$shared = file_get_contents("$src/prompts/shared.md");

$links = '';
foreach ($bgs as [$id, $base, $title, $sub]) {
    $row = ''; $dir = "$out/$base"; if (!is_dir($dir)) mkdir($dir, 0777, true);
    foreach (["$out/$base.html", "$out/$base-prompt.md"] as $old) if (is_file($old)) unlink($old);   // old flat layout
    if (is_file("$src/$id.js")) {
        $bg = preg_replace('/^import .*?;\s*$/m', '', file_get_contents("$src/$id.js"));
        $html = str_replace(['{{TITLE}}', '{{CODE}}'], [htmlspecialchars($title), $core . "\n\n/* ═══════════ $title ═══════════ */\n" . $bg], $tpl);
        file_put_contents("$dir/$base.html", $html);
        echo "built $base/$base.html (" . round(strlen($html) / 1024) . " KB)\n";
        $row .= "<a class=\"go\" href=\"$base/$base.html\">Open scene</a>";
    } else echo "skip $id.html (scene not written yet)\n";
    if (is_file("$src/prompts/$id.md")) {
        $md = "<!-- Generated by build.php from _src/prompts/$id.md + shared.md — edit those, then run: php build.php -->\n"
            . "# Sirpeltric · $title — complete Three.js prompt\n\n"
            . "Paste this whole file into an AI coding tool. It describes ONE single-file HTML background scene.\n"
            . "Reference images exported from the board sit next to this file: `references/` (one folder per board frame); captions, credits and links are in `references.md`; shared art-direction refs are in `../00-brief/`.\n\n"
            . file_get_contents("$src/prompts/$id.md") . "\n\n---\n\n" . $shared;
        file_put_contents("$dir/$base-prompt.md", $md);
        echo "built $base/$base-prompt.md\n";
        $row .= "<a href=\"$base/$base-prompt.md\">Prompt (.md)</a>";
    }
    if (is_file("$dir/references.md")) {
        $n = count(glob("$dir/references/*/*"));
        $row .= "<a href=\"$base/references.md\">References ($n files)</a><a href=\"$base/references/\">Reference folder</a>";
    }
    $links .= "<div class=\"bg\"><b>" . htmlspecialchars($title) . "</b><span>" . htmlspecialchars($sub) . "</span><div class=\"acts\">$row</div></div>\n";
}

if (is_file("$out/00-brief/references.md")) $links = "<div class=\"bg\"><b>00 · Brief + Anime era timeline</b><span>Shared references for all six backgrounds</span><div class=\"acts\"><a href=\"00-brief/references.md\">References</a><a href=\"00-brief/references/\">Reference folder</a></div></div>
" . $links;

$index = <<<HTML
<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Sirpeltric BG References</title>
<style>
:root{--bg:#141416;--panel:#1E1E21;--line:#34343A;--tx:#E6E6E9;--tx2:#9A9AA3;--acc:#2F6FEB}
body{margin:0;background:var(--bg);color:var(--tx);font:14px/1.5 system-ui,sans-serif;padding:32px 16px}
main{max-width:760px;margin:0 auto}h1{font-size:20px;margin:0 0 4px}p{color:var(--tx2);margin:0 0 20px}
.bg{display:flex;flex-direction:column;gap:2px;padding:14px 16px;margin:0 0 10px;background:var(--panel);border:1px solid var(--line);border-radius:8px}
.bg span{color:var(--tx2);font-size:13px}.acts{display:flex;gap:8px;margin-top:8px;flex-wrap:wrap}
.acts a{display:inline-flex;align-items:center;height:34px;padding:0 14px;border-radius:6px;border:1px solid var(--line);color:var(--tx);text-decoration:none;font-weight:600}
.acts a.go{background:var(--acc);border-color:var(--acc);color:#fff}.acts a:hover{border-color:var(--acc)}
</style></head><body><main>
<h1>Sirpeltric · BG references (Three.js)</h1>
<p>One file per background, background only (no characters). Each page exports one long panorama (colour · lineart · base colour), a ZIP with one PNG per element, and a 3D .glb for Blender. Internet is needed once for the Three.js CDN.</p>
$links</main></body></html>
HTML;
file_put_contents("$out/index.html", $index);
echo "built index.html\n";
